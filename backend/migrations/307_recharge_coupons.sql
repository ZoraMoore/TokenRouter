-- 券面和订单抵扣金额用币种最小单位保存。
ALTER TABLE redeem_codes ADD COLUMN coupon_terms JSONB;
ALTER TABLE payment_orders ADD COLUMN coupon_snapshot JSONB;

-- 订单占用券，收到付款后写入核销时间。
CREATE TABLE recharge_coupons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    redeem_code_id BIGINT NOT NULL REFERENCES redeem_codes(id),
    currency VARCHAR(3) NOT NULL CHECK (currency ~ '^[A-Z]{3}$'),
    minimum_minor BIGINT NOT NULL,
    discount_minor BIGINT NOT NULL,
    claimed_at TIMESTAMPTZ NOT NULL,
    order_id BIGINT UNIQUE REFERENCES payment_orders(id),
    consumed_at TIMESTAMPTZ,
    UNIQUE (user_id, redeem_code_id),
    CHECK (discount_minor > 0 AND minimum_minor > discount_minor),
    CHECK (consumed_at IS NULL OR order_id IS NOT NULL)
);

CREATE INDEX idx_recharge_coupons_redeem_code ON recharge_coupons(redeem_code_id);
